// Generates library/src/main/ets/theme/tokens/SparkColors.ets from the semantic token list.
// ArkTS strict mode forbids index signatures, so every token is an explicit @Trace field with an
// explicit CSS-variable mapping. Run: node tools/gen-tokens.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = [
  'background', 'foreground', 'card', 'card-foreground', 'popover', 'popover-foreground',
  'primary', 'primary-foreground', 'secondary', 'secondary-foreground', 'muted', 'muted-foreground',
  'accent', 'accent-foreground', 'destructive', 'destructive-foreground', 'border', 'input', 'ring',
  'chart-1', 'chart-2', 'chart-3', 'chart-4', 'chart-5',
  'sidebar', 'sidebar-foreground', 'sidebar-primary', 'sidebar-primary-foreground',
  'sidebar-accent', 'sidebar-accent-foreground', 'sidebar-border', 'sidebar-ring',
];
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const out = `// AUTO-GENERATED by tools/gen-tokens.mjs — do not edit by hand.
/**
 * Semantic colour tokens, 1:1 with shadcn naming (kebab-case CSS variable → camelCase field).
 * Values are ARGB hex strings "#AARRGGBB".
 */
@ObservedV2
export class SparkColors {
${tokens.map((t) => `  @Trace ${camel(t)}: string = '#FF000000';`).join('\n')}

  /** Copy every token from \`other\`. Equal values do not trigger re-render. */
  copyFrom(other: SparkColors): void {
${tokens.map((t) => `    this.${camel(t)} = other.${camel(t)};`).join('\n')}
  }

  /** Read a token by CSS variable name (without the leading "--"). */
  get(name: string): string | undefined {
    switch (name) {
${tokens.map((t) => `      case '${t}':\n        return this.${camel(t)};`).join('\n')}
      default:
        return undefined;
    }
  }

  /** Write a token by CSS variable name (without "--"). Returns false for unknown names. */
  set(name: string, value: string): boolean {
    switch (name) {
${tokens.map((t) => `      case '${t}':\n        this.${camel(t)} = value;\n        return true;`).join('\n')}
      default:
        return false;
    }
  }
}

/** All semantic colour token names, in shadcn order. */
export const SPARK_COLOR_TOKENS: string[] = [
${tokens.map((t) => `  '${t}',`).join('\n')}
];
`;
writeFileSync(join(root, 'library/src/main/ets/theme/tokens/SparkColors.ets'), out);
console.log(`generated ${tokens.length} tokens`);
